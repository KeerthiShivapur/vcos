"""Background insights API (Phase 9.1 spec path: /insights).

One surface for everything the autonomous organization has learned: the
combined insight feed, the background risk register (strategic risks that the
risk engine derived from intelligence signals) and the autonomous
notifications generated by the notification engine. On-demand scans let
managers force a refresh instead of waiting for the worker cadence.
"""

from typing import Any

from fastapi import APIRouter, Depends, HTTPException, Query
from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.api.deps import get_current_organization, require_permission
from app.db.database import get_db
from app.intelligence.burnout_engine import burnout_engine
from app.intelligence.duplicate_engine import duplicate_engine
from app.intelligence.knowledge_engine import knowledge_engine
from app.intelligence.notification_engine import notification_engine
from app.intelligence.pattern_engine import pattern_engine
from app.intelligence.risk_engine import background_risk_engine
from app.intelligence.search_engine import search_engine
from app.intelligence.workflow_engine import workflow_engine
from app.models.executive import StrategicRisk
from app.models.notification import Notification
from app.models.organization import Organization
from app.models.user import User

router = APIRouter(prefix="/insights", tags=["Intelligence"])


# ------------------------------------------------------------------ combined feed

@router.get("")
async def combined_feed(
    org: Organization = Depends(get_current_organization),
    user: User = Depends(require_permission("intelligence:read")),
    db: AsyncSession = Depends(get_db),
    limit: int = Query(10, ge=1, le=50),
):
    """Latest findings from every background intelligence engine."""
    knowledge = await knowledge_engine.list_insights(db, organization_id=org.id, limit=limit)
    burnout = await burnout_engine.list_signals(
        db, organization_id=org.id, min_level="moderate", limit=limit
    )
    duplicates = await duplicate_engine.list_detections(db, organization_id=org.id, limit=limit)
    patterns = await pattern_engine.list_patterns(db, organization_id=org.id, limit=limit)
    workflow = await workflow_engine.list_insights(db, organization_id=org.id, limit=limit)
    search = await search_engine.list_insights(db, organization_id=org.id, limit=limit)
    risks = await background_risk_engine.list_open(db, organization_id=org.id, limit=limit)
    return {
        "risks": risks,
        "knowledge": knowledge,
        "burnout": burnout,
        "duplicates": duplicates,
        "patterns": patterns,
        "workflow": workflow,
        "search": search,
        "counts": {
            "risks": len(risks),
            "knowledge": len(knowledge),
            "burnout": len(burnout),
            "duplicates": len(duplicates),
            "patterns": len(patterns),
            "workflow": len(workflow),
            "search": len(search),
        },
    }


# ------------------------------------------------------------------ risk register

@router.get("/risks")
async def risk_register(
    org: Organization = Depends(get_current_organization),
    user: User = Depends(require_permission("intelligence:read")),
    db: AsyncSession = Depends(get_db),
    level: str = Query(None),
    status: str = Query("open"),
    limit: int = Query(50, ge=1, le=200),
):
    stmt = select(StrategicRisk).where(StrategicRisk.organization_id == org.id)
    if level:
        stmt = stmt.where(StrategicRisk.level == level)
    if status:
        stmt = stmt.where(StrategicRisk.status == status)
    rows = (await db.execute(stmt.order_by(StrategicRisk.score.desc()).limit(limit))).scalars().all()
    return {
        "total": len(rows),
        "risks": [
            {
                "id": r.id,
                "kind": r.kind,
                "title": r.title,
                "description": r.description,
                "probability": r.probability,
                "impact": r.impact,
                "score": r.score,
                "level": r.level,
                "subject_type": r.subject_type,
                "subject_id": r.subject_id,
                "subject_name": r.subject_name,
                "status": r.status,
                "created_at": r.created_at.isoformat() if r.created_at else None,
            }
            for r in rows
        ],
    }


@router.post("/risks/scan")
async def scan_risks(
    org: Organization = Depends(get_current_organization),
    user: User = Depends(require_permission("intelligence:manage")),
    db: AsyncSession = Depends(get_db),
):
    """Run the background risk scan on demand (normally the risk worker does it)."""
    created = await background_risk_engine.scan(db, organization_id=org.id)
    await db.commit()
    return {"scanned": True, "new_risks": created}


# ------------------------------------------------------------------ autonomous notifications

@router.get("/notifications")
async def autonomous_notifications(
    org: Organization = Depends(get_current_organization),
    user: User = Depends(require_permission("intelligence:read")),
    db: AsyncSession = Depends(get_db),
    type: str = Query(None),
    limit: int = Query(50, ge=1, le=200),
):
    """Notifications the notification engine generated autonomously."""
    stmt = select(Notification).where(
        Notification.organization_id == org.id,
        Notification.type.in_(("risk", "burnout", "pattern")),
    )
    if type:
        stmt = stmt.where(Notification.type == type)
    rows = (await db.execute(stmt.order_by(Notification.created_at.desc()).limit(limit))).scalars().all()
    return [
        {
            "id": n.id,
            "type": n.type,
            "title": n.title,
            "body": n.body,
            "priority": n.priority,
            "link": n.link,
            "entity_type": n.entity_type,
            "entity_id": n.entity_id,
            "recipient_id": n.recipient_id,
            "created_at": n.created_at.isoformat() if n.created_at else None,
        }
        for n in rows
    ]


@router.post("/notifications/generate")
async def generate_notifications(
    org: Organization = Depends(get_current_organization),
    user: User = Depends(require_permission("intelligence:manage")),
    db: AsyncSession = Depends(get_db),
):
    """Run the autonomous notification engine on demand."""
    created = await notification_engine.generate(db, organization_id=org.id)
    await db.commit()
    return {"generated": created}
