@router.patch("/installed/{industry_key}")
async def update_pack(
    industry_key: str,
    payload: dict[str, Any],
    org: Organization = Depends(get_current_organization),
    user: User = Depends(require_permission("industry:manage")),
    db: AsyncSession = Depends(get_db),
):
    config = await industry_plugin_loader.get_config(db, org.id, industry_key)
    if config is None:
        raise HTTPException(status_code=404, detail="Pack not installed")
    if "enabled" in payload:
        await industry_plugin_loader.set_enabled(
            db, organization_id=org.id, industry_key=industry_key,
            enabled=bool(payload["enabled"]), actor_id=user.id,
        )
    if "settings" in payload:
        config.settings = {**(config.settings or {}), **payload["settings"]}
    if "country" in payload:
        config.settings = {**(config.settings or {}), "country": payload["country"]}
    await db.commit()
    return industry_plugin_loader._serialize(db, config)


