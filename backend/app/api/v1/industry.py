@router.post("/installed/{industry_key}/templates/{template_key}/apply")
async def apply_template(
    industry_key: str,
    template_key: str,
    payload: dict[str, Any],
    org: Organization = Depends(get_current_organization),
    user: User = Depends(require_permission("industry:manage")),
    db: AsyncSession = Depends(get_db),
):
    if await industry_plugin_loader.get_config(db, org.id, industry_key) is None:
        raise HTTPException(status_code=404, detail="Pack not installed")
    template = next(
        (t for t in pack_templates(industry_key) if t["key"] == template_key), None
    )
    if template is None:
        raise HTTPException(status_code=404, detail="Template not found")
    workflow_id: Optional[str] = None
    if template.get("kind") == "workflow" and template.get("workflow_key"):
        workflow = await industry_workflow_engine.activate(
            db,
            organization_id=org.id,
            industry_key=industry_key,
            template_key=template["workflow_key"],
            actor_id=user.id,
            context=payload.get("context") or {},
        )
        workflow_id = workflow.id
    await publish_event(
        db,
        name="industry.template.applied",
        organization_id=org.id,
        actor_id=user.id,
        payload={
            "industry_key": industry_key,
            "template_key": template_key,
            "kind": template.get("kind"),
            "workflow_id": workflow_id,
        },
    )
    await db.commit()
    return {
        "industry_key": industry_key,
        "template_key": template_key,
        "name": template["name"],
        "kind": template.get("kind"),
        "content": template.get("content", {}),
        "workflow_id": workflow_id,
    }


