@router.post("/select")
async def select_industry(
    payload: dict[str, Any],
    org: Organization = Depends(get_current_organization),
    user: User = Depends(require_permission("industry:manage")),
    db: AsyncSession = Depends(get_db),
):
    """Choose an industry for the org — installs the pack + records the selection."""
    industry_key = payload.get("industry_key")
    if not industry_key or get_pack(industry_key) is None:
        raise HTTPException(status_code=404, detail="Unknown industry")
    try:
        installed = await industry_plugin_loader.install(
            db,
            organization_id=org.id,
            industry_key=industry_key,
            actor_id=user.id,
        )
        selection = await industry_plugin_loader.select(
            db,
            organization_id=org.id,
            industry_key=industry_key,
            business_type=payload.get("business_type"),
            company_size=payload.get("company_size"),
            country=payload.get("country"),
            regulations=payload.get("regulations"),
            role=payload.get("role", "primary"),
            actor_id=user.id,
        )
    except ValueError as exc:
        raise _http(exc)
    await db.commit()
    return {
        "installed": installed,
        "selection": {
            "industry_key": selection.industry_key,
            "business_type": selection.business_type,
            "company_size": selection.company_size,
            "country": selection.country,
            "regulations": selection.regulations,
            "role": selection.role,
            "status": selection.status,
        },
    }


@router.get("/selections")
async def list_selections(
    org: Organization = Depends(get_current_organization),
    user: User = Depends(require_permission("industry:read")),
    db: AsyncSession = Depends(get_db),
):
    result = await db.execute(
        select(IndustrySelection)
        .where(IndustrySelection.organization_id == org.id)
        .order_by(IndustrySelection.role, IndustrySelection.industry_key)
    )
    return [
        {
            "industry_key": s.industry_key,
            "business_type": s.business_type,
            "company_size": s.company_size,
            "country": s.country,
            "regulations": s.regulations or [],
            "role": s.role,
            "status": s.status,
        }
        for s in result.scalars().all()
    ]


